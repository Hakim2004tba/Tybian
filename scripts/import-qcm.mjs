/**
 * Turns an exported question bank (a folder of JSON files, one per
 * topic) into an idempotent .sql file to run in phpMyAdmin.
 *
 * SQL rather than a live connection, deliberately: this host is
 * reached through phpMyAdmin, the same way every other migration is
 * applied, and a 900-question import that half-finishes over a flaky
 * link is worse than a file that either runs or does not.
 *
 * Re-running is safe. Every row is keyed on its source id and written
 * with INSERT ... ON DUPLICATE KEY UPDATE, so importing twice updates
 * rather than duplicates - the mistake that turns a bank of 869 into
 * a bank of 1738.
 *
 * Usage:
 *   node scripts/import-qcm.mjs <folder> <subject> <slug> [outfile]
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, basename } from "node:path";
import { createHash } from "node:crypto";

const [, , folder, subjectName, subjectSlug, outArg] = process.argv;
if (!folder || !subjectName || !subjectSlug) {
  console.error("usage: node scripts/import-qcm.mjs <folder> <subject> <slug> [out.sql]");
  process.exit(1);
}
/*
   A FOLDER OF SMALL FILES, not one big one.

   phpMyAdmin's default upload cap is 2 MB and this bank is 2.0 MB, so
   a single file is a coin toss on the host's settings. One file per
   topic is ~110 KB, imports in any configuration, and lets an
   interrupted import resume at the topic that failed rather than from
   the beginning.
*/
const outDir = outArg ?? `../tibyan-db/mysql/qcm-${subjectSlug}`;

/* Deterministic ids, so a re-run writes the SAME rows instead of a
   second copy with fresh uuids. */
const idFor = (...parts) =>
  createHash("sha1").update(parts.join(" ")).digest("hex").slice(0, 32)
    .replace(/^(.{8})(.{4})(.{4})(.{4})(.{12}).*$/, "$1-$2-$3-$4-$5");

const q = (v) => {
  if (v === null || v === undefined) return "NULL";
  return "'" + String(v).replace(/\\/g, "\\\\").replace(/'/g, "''") + "'";
};

const slugify = (s) =>
  s.toLowerCase().normalize("NFD").replace(/\p{M}/gu, "")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 180) || "topic";

const files = readdirSync(folder).filter((f) => f.endsWith(".json")).sort();
const subjectId = idFor("subject", subjectSlug);

mkdirSync(outDir, { recursive: true });

const header = [
  `-- ${subjectName} - generated by scripts/import-qcm.mjs. Do not edit by hand.`,
  "-- Re-run after any source update: it updates rather than duplicates.",
  "",
];

/* The subject starts ACTIVE because its questions are here; every
   other subject stays "coming soon" until its own import runs. */
writeFileSync(
  join(outDir, "00-subject.sql"),
  header.concat([
    "INSERT INTO qcm_subjects (id, name, slug, is_active, sort_order) VALUES " +
      `(${q(subjectId)}, ${q(subjectName)}, ${q(subjectSlug)}, 1, 0) ` +
      "ON DUPLICATE KEY UPDATE name = VALUES(name), is_active = 1;",
    "",
  ]).join("\n"),
  "utf8"
);

let totalQ = 0;
let totalMedia = 0;

files.forEach((file, topicIndex) => {
  const lines = header.slice();
  const data = JSON.parse(readFileSync(join(folder, file), "utf8"));
  const title = data.title ?? basename(file, ".json");
  const topicSlug = slugify(title);
  const topicId = idFor("topic", subjectSlug, topicSlug);

  lines.push(`-- ${title} (${data.questions?.length ?? 0})`);
  lines.push(
    "INSERT INTO qcm_topics (id, subject_id, title, slug, sort_order) VALUES " +
      `(${q(topicId)}, ${q(subjectId)}, ${q(title)}, ${q(topicSlug)}, ${topicIndex}) ` +
      "ON DUPLICATE KEY UPDATE title = VALUES(title), sort_order = VALUES(sort_order);"
  );

  (data.questions ?? []).forEach((question, i) => {
    const meta = question.metadata ?? {};
    const external = String(question.original_id ?? question.id ?? `${topicSlug}-${i}`);
    const questionId = idFor("question", topicId, external);

    const kind = String(meta.type ?? "QCU").toUpperCase() === "QCM" ? "qcm" : "qcu";
    const statement = question.statement ?? question.question ?? "";
    const media = question.media_urls ?? [];
    const tags = meta.tags ?? [];
    totalMedia += media.length;

    lines.push(
      "INSERT INTO qcm_questions (id, topic_id, kind, statement, explanation, media, tags, external_id, sort_order) VALUES " +
        `(${q(questionId)}, ${q(topicId)}, '${kind}', ${q(statement)}, ${q(question.explanation ?? null)}, ` +
        `${media.length ? q(JSON.stringify(media)) : "NULL"}, ${tags.length ? q(JSON.stringify(tags)) : "NULL"}, ` +
        `${q(external)}, ${i}) ` +
        "ON DUPLICATE KEY UPDATE kind = VALUES(kind), statement = VALUES(statement), " +
        "explanation = VALUES(explanation), media = VALUES(media), tags = VALUES(tags), sort_order = VALUES(sort_order);"
    );

    (question.options ?? []).forEach((option, j) => {
      const letter = (option.letter ?? String.fromCharCode(65 + j)).slice(0, 1);
      lines.push(
        "INSERT INTO qcm_options (id, question_id, letter, body, is_correct, position) VALUES " +
          `(${q(idFor("option", questionId, letter))}, ${q(questionId)}, ${q(letter)}, ` +
          `${q(option.text ?? "")}, ${option.is_correct ? 1 : 0}, ${j}) ` +
          "ON DUPLICATE KEY UPDATE body = VALUES(body), is_correct = VALUES(is_correct), position = VALUES(position);"
      );
    });

    totalQ++;
  });

  const name = `${String(topicIndex + 1).padStart(2, "0")}-${topicSlug}.sql`;
  writeFileSync(join(outDir, name), lines.join("\n") + "\n", "utf8");
});

console.log(
  `${files.length} topics, ${totalQ} questions, ${totalMedia} media -> ${outDir}/`
);
